package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

// A module that needs no host function still gets its output file, so that
// a file left by an earlier build (with methods the module now defines
// itself) never stays behind.
func Test_noImports(t *testing.T) {
	out := filepath.Join(t.TempDir(), "libc.go")
	if err := os.WriteFile(out, []byte("stale"), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("go", "run", ".", "-pkg", "fib", "-wasm", "../testdata/fib/fib.wasm", "-o", out)
	if b, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%v\n%s", err, b)
	}
	b, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	const want = "// Code generated by libc-gen. DO NOT EDIT.\n\npackage fib\n"
	if string(b) != want {
		t.Errorf("got %q, want %q", b, want)
	}
}
