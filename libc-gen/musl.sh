#!/usr/bin/env bash
# musl.sh: vendors the double-precision functions of musl's libm into c/libm
# and generates c/libm.c, which libc.c includes.
#
# The tarball is downloaded to tools/ (see tools.sh, which this script needs
# for clang and llvm-nm) and checked against its SHA-256, which was pinned
# after checking the release's signature (musl-$VERSION.tar.gz.asc) against
# musl's key, fingerprint 8364 8929 0BB6 B70F 99FF DA05 56BC DB59 3020 450F. The listed source
# files and musl's COPYRIGHT are copied unchanged; c/libm/libm.h and
# c/libm/atomic.h replace musl's internal headers and are not touched here.
#
# libc.c is a single translation unit, so libm.c renames every file-scope
# static of each musl file (musl's files reuse names such as pio2_hi) with a
# prefix naming the file, and undefines the file's macros after it.
set -euo pipefail

cd -P -- "$(dirname -- "$0")"

VERSION=1.2.6
SHA256=d585fd3b613c66151fc3249e8ed44f77020cb5e6c1e635a616d3f9f82460512a
URL="https://musl.libc.org/releases/musl-$VERSION.tar.gz"

# The functions math.h declares that are not compiler builtins, and what
# they call, except fma.
FILES=(
	acos acosh asin asinh atan atan2 atanh cbrt cos cosh erf exp exp2 expm1
	fdim fmax fmin fmod frexp hypot ilogb j0 j1 jn ldexp lgamma lgamma_r
	log log10 log1p log2 logb modf nextafter pow remainder round sin sinh tan
	tanh tgamma
	__cos __expo2 __math_divzero __math_invalid __math_oflow __math_uflow
	__math_xflow __rem_pio2 __rem_pio2_large __sin __tan exp_data log2_data
	log_data pow_data remquo scalbn signgam
)
HEADERS=(exp_data.h log2_data.h log_data.h pow_data.h)
# Copied but not compiled: fma is a Go host function (go/math.go), and musl's
# fma is what scripts/libm-reference.sh checks it against.
REFERENCE=(fma)

WASI_SDK=tools/wasi-sdk/bin
tarball="tools/musl-$VERSION.tar.gz"
src="tools/musl-$VERSION"
out=c/libm

if [ ! -f "$tarball" ]; then
	mkdir -p tools
	curl -#Lo "$tarball" "$URL"
fi
echo "$SHA256  $tarball" | sha256sum -c -
tar xzf "$tarball" -C tools

mkdir -p "$out"
cp "$src/COPYRIGHT" "$out/COPYRIGHT"
for h in "${HEADERS[@]}"; do
	cp "$src/src/math/$h" "$out/$h"
done
for f in "${FILES[@]}" "${REFERENCE[@]}"; do
	cp "$src/src/math/$f.c" "$out/$f.c"
done

cflags=(--target=wasm32 -ffreestanding -nostdlib -std=c23 -O0 -w -Xclang -femit-all-decls -include features.h -I c -I "$out")

# locals <file.c>: the file-scope statics an object file defines.
locals() {
	"$WASI_SDK/clang" "${cflags[@]}" -c -o "$src/obj.o" "$1"
	"$WASI_SDK/llvm-nm" --defined-only "$src/obj.o" | awk '$2 ~ /^[a-z]$/ && $3 !~ /\./ { print $3 }' | sort -u
}

# macros <file.c>: the macros defined at the end of a file.
macros() {
	"$WASI_SDK/clang" "${cflags[@]}" -E -dM "$1" | awk '{ sub(/\(.*/, "", $2); print $2 }' | sort -u
}

# The statics and macros of the headers are shared by every file, and not
# renamed or undefined.
{
	echo '#include "libm.h"'
	echo '#include "atomic.h"'
	for h in "${HEADERS[@]}"; do echo "#include \"$h\""; done
} >"$src/headers.c"
locals "$src/headers.c" >"$src/headers.txt"
macros "$src/headers.c" >"$src/headers.macros"

{
	echo "// Code generated by musl.sh. DO NOT EDIT."
	echo
	echo "// The double-precision functions of musl $VERSION's libm (libm/COPYRIGHT)."
	echo "// Each file's statics are renamed and its macros undefined after it,"
	echo "// since they are compiled in a single translation unit."
	echo
	echo "#pragma clang diagnostic push"
	echo "#pragma clang diagnostic ignored \"-Weverything\""
	echo "#include <features.h>"
	for f in "${FILES[@]}"; do
		echo
		syms=$(locals "$out/$f.c" | comm -23 - "$src/headers.txt")
		for s in $syms; do
			echo "#define $s __libm_${f}_$s"
		done
		echo "#include \"libm/$f.c\""
		for s in $syms; do
			echo "#undef $s"
		done
		{ cat "$src/headers.c"; echo "#include \"$PWD/$out/$f.c\""; } >"$src/file.c"
		macros "$src/file.c" >"$src/file.macros"
		if [ -n "$(comm -13 "$src/file.macros" "$src/headers.macros")" ]; then
			echo "musl.sh: $f.c undefines a macro of the headers" >&2
			exit 1
		fi
		for m in $(comm -23 "$src/file.macros" "$src/headers.macros"); do
			echo "#undef $m"
		done
	done
	echo
	echo "#undef hidden"
	echo "#undef weak_alias"
	echo "#pragma clang diagnostic pop"
} >c/libm.c
