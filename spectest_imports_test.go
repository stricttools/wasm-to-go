package main

import (
	"bytes"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

const spectestImportPrefix = "github.com/stricttools/wasm-to-go/internal/spectest/"

// isGeneratedGoFile reports whether src carries Go's generated-code marker.
func isGeneratedGoFile(src []byte) bool {
	for _, line := range bytes.Split(src, []byte("\n")) {
		s := string(bytes.TrimSpace(line))
		if strings.HasPrefix(s, "package ") {
			return false
		}
		if strings.HasPrefix(s, "// Code generated ") && strings.HasSuffix(s, " DO NOT EDIT.") {
			return true
		}
	}
	return false
}

// hasHandWrittenGoFile reports whether dir holds a Go file the go command
// reads that is not generated.
func hasHandWrittenGoFile(t *testing.T, dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasPrefix(name, "_") || strings.HasPrefix(name, ".") {
			continue
		}
		src, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		if !isGeneratedGoFile(src) {
			return true
		}
	}
	return false
}

// The spec-suite packages under internal/spectest are generated by the
// translate tests and are not committed, so a hand-written Go file the go
// command reads must not import one: in a fresh checkout the import has no
// package, and `go mod tidy` there fails looking for a module that provides
// it. Hand-written tests of generated packages are kept as _<name>_test.go,
// which the go command ignores, and the translate tests copy them into place.
func Test_spectestHandWrittenFilesImportNoGeneratedPackage(t *testing.T) {
	fset := token.NewFileSet()
	err := filepath.WalkDir("internal/spectest", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		if d.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasPrefix(name, "_") || strings.HasPrefix(name, ".") {
			return nil
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if isGeneratedGoFile(src) {
			return nil
		}
		f, err := parser.ParseFile(fset, path, src, parser.ImportsOnly)
		if err != nil {
			return err
		}
		for _, imp := range f.Imports {
			p, err := strconv.Unquote(imp.Path.Value)
			if err != nil {
				return err
			}
			rel, ok := strings.CutPrefix(p, spectestImportPrefix)
			if !ok {
				continue
			}
			if !hasHandWrittenGoFile(t, filepath.Join("internal/spectest", filepath.FromSlash(rel))) {
				t.Errorf("%s imports %s, a generated package that is not committed; keep the file as _%s so the go command ignores it, and let the translate tests copy it into place", path, p, name)
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}
